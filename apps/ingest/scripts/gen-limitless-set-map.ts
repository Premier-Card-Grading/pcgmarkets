// Run from the repo root: pnpm tsx apps/ingest/scripts/gen-limitless-set-map.ts  (reads the DB, ~5 min at 1 req/s)
import "dotenv/config";
import { writeFileSync } from "node:fs";
import { createServiceClient, selectAll } from "@pcg/db";
import { limitless } from "@pcg/connectors";

const db = createServiceClient();
const ours = await selectAll<{ id: string; name_ja: string | null; release_date: string | null }>((f, t) =>
  db.from("sets").select("id,name_ja,release_date").eq("language", "ja").order("id").range(f, t));
const byCode = new Map(ours.map((s) => [s.id.toLowerCase().replace(/^ja-/, ""), s.id]));
// Limitless tooltips wrap the title in a product type, e.g. 拡張パック「ブラックコレクション」; ours hold the bare title.
const bare = (n: string | null | undefined) => n?.match(/「(.+)」/)?.[1] ?? n ?? null;
// Hand-verified pairings (same Japanese title live on both sites); merged last and take precedence.
const MANUAL: Record<string, string> = { SVP: "SV-P", MP: "M-P" };
const map: Record<string, string> = {};
const unmatchedOurs = new Set(ours.map((s) => s.id));
const claimed = new Set<string>();
const byId = new Map(ours.map((o) => [o.id, o]));
const pages: { s: Awaited<ReturnType<typeof limitless.listSets>>[number]; name: string | null; date: string | null; direct: string | undefined }[] = [];
for (const s of await limitless.listSets()) {
  const page = await limitless.getSet(s.code);
  pages.push({ s, name: bare(page.nameJa), date: page.releaseDate ?? s.releaseDate, direct: byCode.get(s.code.toLowerCase()) });
}
// Pass 1: a code match stands when the Japanese names agree (or either is unknown). Codes can collide across
// different sets (Limitless BW1b is Black Collection, our BW1b is White Collection), so disagreeing ones wait for pass 2.
const pending: typeof pages = [];
for (const p of pages) {
  const o = p.direct ? byId.get(p.direct)! : undefined;
  if (o && (!o.name_ja || !p.name || o.name_ja === p.name)) {
    if (o.id !== p.s.code) map[p.s.code] = o.id;
    claimed.add(o.id); unmatchedOurs.delete(o.id);
  } else pending.push(p);
}
// Pass 2: exact Japanese name AND release date, only onto sets nothing else claimed.
const unresolved: typeof pages = [];
for (const p of pending) {
  const hit = ours.filter((o) => !claimed.has(o.id) && o.name_ja && o.name_ja === p.name && o.release_date === p.date);
  if (hit.length === 1) { map[p.s.code] = hit[0]!.id; claimed.add(hit[0]!.id); unmatchedOurs.delete(hit[0]!.id); }
  else if (hit.length > 1) console.warn(`AMBIGUOUS ${p.s.code}: ${hit.map((h) => h.id).join(", ")}`);
  else unresolved.push(p);
}
// Pass 3: names disagree and nothing better matched: keep the code match, flag for review.
for (const p of unresolved) {
  if (!p.direct || claimed.has(p.direct)) continue;
  console.warn(`CODE-ONLY ${p.s.code} -> ${p.direct} (${p.name} vs ${byId.get(p.direct)!.name_ja})`);
  if (p.direct !== p.s.code) map[p.s.code] = p.direct;
  claimed.add(p.direct); unmatchedOurs.delete(p.direct);
}
for (const [k, v] of Object.entries(MANUAL)) { map[k] = v; unmatchedOurs.delete(v); }
const body = Object.entries(map).sort(([a], [b]) => a.localeCompare(b)).map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`).join("\n");
writeFileSync(new URL("../../../packages/connectors/src/limitless/ja-set-map.ts", import.meta.url), `/**
 * Limitless code -> our set id, where they differ. Generated by apps/ingest/scripts/gen-limitless-set-map.ts on ${new Date().toISOString().slice(0, 10)}
 * (exact code match ignoring case, else exact Japanese name AND release date). Reviewed before commit.
 */
export const LIMITLESS_TO_OURS: Record<string, string> = {
${body}
};

export function ourSetIdFor(limitlessCode: string, ourIds: ReadonlySet<string>): string | null {
  const mapped = LIMITLESS_TO_OURS[limitlessCode];
  if (mapped) return mapped;
  if (ourIds.has(limitlessCode)) return limitlessCode;
  const lower = limitlessCode.toLowerCase();
  for (const id of ourIds) if (id.toLowerCase() === lower || id.toLowerCase() === \`ja-\${lower}\`) return id;
  return null;
}
`);
console.log(`mapped ${Object.keys(map).length}; our JA sets with no Limitless match: ${[...unmatchedOurs].sort().join(", ")}`);
